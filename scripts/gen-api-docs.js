#!/usr/bin/env node
/**
 * Generates docs/API.md from the Express route files, so the endpoint list can't
 * drift from the code:  node scripts/gen-api-docs.js
 *
 * It reads mounts in backend/server.js (and routes/admin/index.js) plus every
 * router.<method>(path, ...middleware) call, and reports the auth each endpoint
 * gets from its mount, any router.use(), and its own middleware.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const BACKEND = path.join(ROOT, 'backend');
const GUARDS = ['protect', 'protectOptional', 'admin', 'staffOrAdmin', 'csrfProtection'];

const read = (p) => fs.readFileSync(p, 'utf8');
const guardsIn = (text) => GUARDS.filter((g) => new RegExp(`\\b${g}\\b`).test(text));

// app.use('/api/x', mw, require('./routes/file')) / router.use(require('./file'))
function mounts(file, base) {
  const src = read(file);
  const out = [];
  const re = /^(?:app|router)\.use\(\s*(?:'([^']+)'\s*,)?([^;\n]*?)require\('([^']+)'\)\s*\);/gm;
  let m;
  const add = (prefix, middleware, request) => {
    const target = require.resolve(path.resolve(path.dirname(file), request));
    if (!target.includes(`${path.sep}routes${path.sep}`)) return;
    out.push({ prefix: (base + (prefix || '')).replace(/\/$/, '') || '/', guards: guardsIn(middleware), file: target });
  };
  while ((m = re.exec(src))) add(m[1], m[2], m[3]);
  // const userRoutes = require('./routes/userRoutes'); ... app.use('/api/users', userRoutes);
  for (const [, name, request] of src.matchAll(/^const (\w+) = require\('(\.\/routes\/[^']+)'\);/gm)) {
    const use = src.match(new RegExp(`^(?:app|router)\\.use\\(\\s*'([^']+)'\\s*,([^;\\n]*?)\\b${name}\\s*\\);`, 'm'));
    if (use) add(use[1], use[2], request);
  }
  return out;
}

function routes(file) {
  let src = read(file);
  // Resolve aliased imports: const { protect: dbProtect } = require('../middleware/authMiddleware')
  for (const [, names] of src.matchAll(/const \{([^}]+)\} = require\('[^']*authMiddleware'\)/g)) {
    for (const [, real, alias] of names.matchAll(/(\w+)\s*:\s*(\w+)/g)) {
      src = src.replace(new RegExp(`\\b${alias}\\b`, 'g'), real);
    }
  }
  const routerUse = [...src.matchAll(/^router\.use\(([^)]*)\)/gm)].flatMap((m) => guardsIn(m[1]));
  const list = [];
  const re = /^router\.(get|post|put|patch|delete)\(\s*([^,]+),([^\n]*)/gm;
  let m;
  while ((m = re.exec(src))) {
    let p = m[2].trim();
    const constant = /^[A-Z_]+$/.test(p) && src.match(new RegExp(`const ${p} = '([^']+)'`));
    p = constant ? constant[1] : p.replace(/^'|'$/g, '');
    p = p.replace(/\(USER\\\\d\+\)/, '');
    list.push({ method: m[1].toUpperCase(), path: p, guards: [...routerUse, ...guardsIn(m[3])] });
  }
  return list;
}

function collect() {
  const rows = [];
  const add = (mount, guards) => {
    for (const r of routes(mount.file)) {
      rows.push({ ...r, guards: [...guards, ...r.guards], file: mount.file, prefix: mount.prefix });
    }
  };
  for (const mount of mounts(path.join(BACKEND, 'server.js'), '')) {
    add(mount, mount.guards);
    // Aggregating routers (routes/admin/index.js) mount sub-routers at '/'.
    if (path.basename(mount.file) === 'index.js') {
      const routerUse = [...read(mount.file).matchAll(/^router\.use\((\w+)\);/gm)].flatMap((m) => guardsIn(m[1]));
      for (const sub of mounts(mount.file, mount.prefix)) add(sub, [...mount.guards, ...routerUse, ...sub.guards]);
    }
  }
  return rows;
}

function access(guards) {
  const g = new Set(guards);
  const who = g.has('admin') ? 'admin' : g.has('staffOrAdmin') ? 'staff, admin' : g.has('protect') ? 'signed in'
    : g.has('protectOptional') ? 'public (user-aware)' : 'public';
  return g.has('csrfProtection') ? `${who} + CSRF` : who;
}

const rows = collect();
const byFile = new Map();
for (const r of rows) {
  const key = path.relative(BACKEND, r.file);
  if (!byFile.has(key)) byFile.set(key, []);
  byFile.get(key).push(r);
}

let md = `# API reference

> Generated by \`node scripts/gen-api-docs.js\` from the route files — don't edit by
> hand. ${rows.length} endpoints.

Every response uses the envelope \`{ status: 'SUCCESS' | 'FAIL', message, keyValueTable }\`
(\`backend/utils/responseFormatter.js\`). Browsers call these through the storefront
proxy (\`/api/*\` on :3000), never the backend port directly.

**Access:** *public* — no auth; *public (user-aware)* — optional auth changes the
result; *signed in* — any valid token; *staff, admin* / *admin* — role required
(401 without auth, 403 with the wrong role); *+ CSRF* — state-changing calls need
the \`X-CSRF-Token\` header matching the \`csrf_token\` cookie (from
\`GET /api/users/csrf-token\`). Writes under \`/api/admin\` always need CSRF.
`;
for (const [file, list] of [...byFile].sort()) {
  md += `\n## \`${list[0].prefix}\` — ${file}\n\n| Method | Path | Access |\n|---|---|---|\n`;
  for (const r of list) {
    const full = (r.prefix + (r.path === '/' ? '' : r.path)) || '/';
    const isWrite = r.method !== 'GET';
    const guards = isWrite ? r.guards : r.guards.filter((g) => g !== 'csrfProtection');
    md += `| ${r.method} | \`${full}\` | ${access(guards)} |\n`;
  }
}
fs.writeFileSync(path.join(ROOT, 'docs', 'API.md'), md);
console.log(`docs/API.md: ${rows.length} endpoints from ${byFile.size} route files`);
